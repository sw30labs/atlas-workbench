"""Pre-write snapshots of the files that hold unregenerable human judgment.

ADR-012 gitignores runtime artifacts because they are regenerated by pipeline
runs. That reasoning holds for `atlas.db` and `generated/`, but not for the
emerging-risk register: no re-run reproduces a human review decision. On
2026-08-04 a monitoring cycle overwrote the register's review states and
accreted raw URLs into `evidence_refs`, and every backup that existed had been
taken afterwards — the pre-damage content was simply gone.

So the register is snapshotted immediately before it is replaced, by the writer
itself rather than by whoever remembers to run a script. The snapshot is
best-effort: a failure here is logged and never blocks a legitimate write,
because refusing to save real work in order to protect a copy of it is the
wrong trade.

Snapshots live under `generated/`, which is gitignored, and are pruned to a
bounded count so an hourly pipeline cannot fill the disk.
"""

from __future__ import annotations

import hashlib
import logging
import shutil
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger(__name__)

SNAPSHOT_ROOT = Path("generated") / "snapshots"
MAX_SNAPSHOTS = 200


def _digest(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def _prune(directory: Path, keep: int) -> None:
    snapshots = sorted(
        (p for p in directory.iterdir() if p.is_file()),
        key=lambda p: p.name,
    )
    for stale in snapshots[: max(0, len(snapshots) - keep)]:
        try:
            stale.unlink()
        except OSError:  # pragma: no cover - racing prune, harmless
            logger.debug("could not prune snapshot %s", stale)


def snapshot_before_write(
    path: str | Path,
    *,
    root: str | Path | None = None,
    keep: int = MAX_SNAPSHOTS,
) -> Path | None:
    """Copy ``path`` aside before a caller replaces it.

    Returns the snapshot path, or None when there was nothing to preserve
    (first write), the content is byte-identical to the newest snapshot
    (an unchanged rewrite), or the copy failed.
    """
    source = Path(path)
    if not source.is_file():
        return None

    try:
        base = Path(root) if root is not None else source.resolve().parent / SNAPSHOT_ROOT
        directory = base / source.stem
        directory.mkdir(parents=True, exist_ok=True)

        current = _digest(source)
        existing = sorted(p for p in directory.iterdir() if p.is_file())
        if existing and current is not None and _digest(existing[-1]) == current:
            return None  # nothing changed since the last snapshot

        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%f")
        target = directory / f"{source.stem}-{stamp}{source.suffix}"
        shutil.copy2(source, target)
        _prune(directory, keep)
        return target
    except OSError as exc:
        # Never block the write: the caller is saving real work.
        logger.warning("could not snapshot %s before write: %s", source, exc)
        return None


def snapshot_dir_for(path: str | Path, *, root: str | Path | None = None) -> Path:
    """Where snapshots of ``path`` are kept."""
    source = Path(path)
    base = Path(root) if root is not None else source.resolve().parent / SNAPSHOT_ROOT
    return base / source.stem


__all__ = ["snapshot_before_write", "snapshot_dir_for", "MAX_SNAPSHOTS"]
